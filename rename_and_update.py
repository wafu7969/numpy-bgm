for num, (old_name, new_title, desc) in mapping.items():
    old_path = os.path.join("examples", old_name)
    new_name = f"{num}_{old_name}"
    new_path = os.path.join("examples", new_name)
    
    if os.path.exists(old_path):
        with open(old_path, "r", encoding="utf-8") as f:
            content = f.read()
            
        # Replace the first line title
        # For example: """示例 11 · 音效与配音展示 —— ...
        content = re.sub(r'^\"\"\"示例 \d+\s*·[^\n]*', f'"""示例 {new_title} ——', content)
        
        # Insert description before the closing """
        parts = content.split('"""', 2)
        if len(parts) >= 3:
            doc = parts[1]
            if "核心编曲与声音设计" not in doc:
                doc = doc.rstrip() + "\n\n" + desc.strip() + "\n"
            parts[1] = doc
            content = '"""' + parts[1] + '"""' + parts[2]
            
        with open(new_path, "w", encoding="utf-8") as f:
            f.write(content)
            
        os.remove(old_path)
